#请求
#1，请求行     请求方式（get/post）请求url地址 协议
#2，请求头     服务器要的一些附加信息，一些反爬的内容
#3，请求体     一般放请求参数

#响应
#1，状态行      状态码，协议 202，404，500，302
#2.响应头       客户端的附加信息
#3，响应体      服务器返回的html源代码，json


#请求头的重要内容：
#1.User-Agent:请求载体的身份标识
#2.Referer：防盗链
#3.cookie：用户的登录状态

#响应头的重要内容：
#1.cookie：用户的登录状态
#2.各种奇妙字符

